create table feriado (
    id          uuid         not null primary key,
    praca       varchar(3)   not null,
    data        date         not null,
    descricao   varchar(80)  not null,
    constraint uk_feriado_praca_data unique (praca, data)
);

create index ix_feriado_praca on feriado (praca, data);

